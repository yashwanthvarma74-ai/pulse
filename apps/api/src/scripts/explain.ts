// Prints the query plan of the feed query for the first page and a page deep in the feed, and writes
// it to docs/explain/feed.md so the plans are committed next to the code that depends on them.
//
//   npm run explain
import { writeFile } from 'node:fs/promises';
import { arch, platform } from 'node:os';
import { fileURLToPath } from 'node:url';
import type { Document, ObjectId } from 'mongodb';
import { FEED_DEFAULT_PAGE_SIZE } from '@pulse/shared';
import { loadConfig } from '../config';
import { connect } from '../db';
import { feedFilter } from '../services/feed';

const config = loadConfig();
const database = await connect(config.MONGODB_URI);
const total = await database.posts.countDocuments({ visibility: 'public' });

async function explain(label: string, after?: { createdAt: Date; id: ObjectId }) {
  const plan = await database.posts
    .find(feedFilter(after))
    .sort({ createdAt: -1, _id: -1 })
    .limit(FEED_DEFAULT_PAGE_SIZE + 1)
    .explain('executionStats');

  const stats = plan.executionStats as Document;
  const stages: string[] = [];
  for (
    let stage = plan.queryPlanner.winningPlan as Document | undefined;
    stage;
    stage = stage.inputStage
  ) {
    stages.push(stage.indexName ? `${stage.stage} (${stage.indexName})` : String(stage.stage));
  }

  return [
    `### ${label}`,
    '',
    `- Plan: ${stages.join(' → ')}`,
    `- Documents returned: ${stats.nReturned}`,
    `- Index keys examined: ${stats.totalKeysExamined}`,
    `- Documents examined: ${stats.totalDocsExamined}`,
    `- Execution time: ${stats.executionTimeMillis} ms`,
    '',
  ].join('\n');
}

const rows = await database.posts
  .find({ visibility: 'public' })
  .sort({ createdAt: -1, _id: -1 })
  .skip(Math.floor(total / 2))
  .limit(1)
  .toArray();
const middle = rows[0];

const sections = [await explain('First page (no cursor)')];
if (middle) {
  sections.push(
    await explain(`A page in the middle of the feed (after post ${Math.floor(total / 2)})`, {
      createdAt: middle.createdAt,
      id: middle._id,
    }),
  );
}

const version = (await database.db.admin().serverInfo()).version;
const body = [
  '# Feed query plans',
  '',
  'Generated by `npm run explain`. The query is `find({ visibility: "public", ...cursorRange })`,',
  `sorted by \`{ createdAt: -1, _id: -1 }\`, limit ${FEED_DEFAULT_PAGE_SIZE + 1} (one extra row tells the API if another page exists).`,
  'The index is `{ visibility: 1, createdAt: -1, _id: -1 }`.',
  '',
  `Dataset: ${total} public posts from \`npm run seed\`. MongoDB ${version}, ${platform()} ${arch()}.`,
  '',
  ...sections,
].join('\n');

await writeFile(fileURLToPath(new URL('../../../../docs/explain/feed.md', import.meta.url)), body);
console.log(body);
await database.client.close();
